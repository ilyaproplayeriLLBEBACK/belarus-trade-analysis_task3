def make_dataset(seed: int = 42, kappa: float = 60.0, base_scale: float = 8.0) -> pd.DataFrame:
    """Генерирует таблицу country × group.

    kappa     — концентрация Дирихле: больше → страны ближе к профилю архетипа (меньше шума).
    base_scale — масштаб «условных единиц» объёма торговли.
    Возвращает широкую таблицу: iso3, country, true_archetype, volume, value по 10 группам.
    """
    rng = np.random.default_rng(seed)
    arch_keys = list(ARCHETYPES)
    prof = {k: np.array(v[1], float) / np.sum(v[1]) for k, v in ARCHETYPES.items()}
    rows = []
    for iso, (name, mix, scale) in COUNTRIES.items():
        w = np.zeros(len(arch_keys))
        for k, v in mix.items():
            w[arch_keys.index(k)] = v
        if len(mix) == 1:  # «чистые» страны получают небольшую случайную примесь
            noise = rng.dirichlet(np.ones(len(arch_keys)))
            w = 0.85 * w + 0.15 * noise
        w = w / w.sum()
        p = sum(w[i] * prof[k] for i, k in enumerate(arch_keys))
        p = rng.dirichlet(kappa * p + 1e-3)
        volume = base_scale * scale * rng.lognormal(0, 0.25)  # усл. ед.
        n = max(40, int(volume * 25))  # число «сделок»: у малых стран мало, отсюда нули и шум
        counts = rng.multinomial(n, p)
        rows.append(
            dict(iso3=iso, country=name, true_archetype=arch_keys[int(np.argmax(w))], volume=volume,
                 **{g: c / n * volume for g, c in zip(GROUPS, counts)})
        )
    df = pd.DataFrame(rows)
    return df


def to_long(df: pd.DataFrame) -> pd.DataFrame:
    return df.melt(id_vars=["iso3", "country", "true_archetype", "volume"], value_vars=GROUPS,
                   var_name="group", value_name="value")


def load_matrix(path: str | Path | None = None, seed: int = 42, kappa: float = 60.0) -> tuple[pd.DataFrame, bool]:
    """Возвращает (wide, is_synthetic).

    Если path указан — читает РЕАЛЬНЫЕ данные в длинном формате (country, iso3, group, value),
    иначе генерирует синтетические. Колонка true_archetype у реальных данных отсутствует.
    """
    if path is not None:
        long = pd.read_csv(path)
        wide = long.pivot_table(index=["iso3", "country"], columns="group", values="value", aggfunc="sum").fillna(0)
        wide = wide.reset_index()
        wide["volume"] = wide[[c for c in wide.columns if c not in ("iso3", "country")]].sum(axis=1)
        return wide, False
    return make_dataset(seed=seed, kappa=kappa), True


